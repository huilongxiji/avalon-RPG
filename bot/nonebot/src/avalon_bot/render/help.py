def render_help(*, superuser: bool = False, prefix: str = ''):
    # 延迟加载 Pillow/NoneBot，纯 HTTP 指令客户端无需图片依赖。
    from .help_layout import HelpItem, HelpPage, HelpSection, render

    sections = []
    for group in ('角色', '背包', '交易', '副本', '其他', '超管'):
        items = []
        for c in COMMANDS:
            if (c.admin and not superuser) or ('超管' if c.admin else c.group) != group:
                continue
            usage = f'{prefix}{c.name} {c.usage}'.rstrip()
            if c.aliases:
                usage += '（别名：' + '、'.join(prefix + a for a in c.aliases) + '）'
            items.append(HelpItem(usage, DESCRIPTIONS.get(c.name, '').replace('{prefix}', prefix)))
        if items:
            sections.append(HelpSection(group, '', tuple(items)))
    return render(HelpPage('指令菜单', f"前缀：{prefix or '（无）'}", '<尖括号>必填  [方括号]可选', tuple(sections)))
